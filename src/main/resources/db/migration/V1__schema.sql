CREATE TABLE event (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(160)             NOT NULL,
    venue     VARCHAR(160)             NOT NULL,
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- A hold reserves seats for a few minutes until it is confirmed (paid), released, or expires.
CREATE TABLE seat_hold (
    id              UUID                     PRIMARY KEY,
    event_id        BIGINT                   NOT NULL REFERENCES event (id),
    customer_email  VARCHAR(254)             NOT NULL,
    status          VARCHAR(12)              NOT NULL,
    seat_count      INTEGER                  NOT NULL,
    total_price_vnd BIGINT                   NOT NULL,
    idempotency_key VARCHAR(80)              NOT NULL,
    request_hash    VARCHAR(64)              NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT chk_hold_status CHECK (status IN ('HELD', 'CONFIRMED', 'RELEASED', 'EXPIRED')),
    CONSTRAINT chk_hold_seat_count CHECK (seat_count > 0),
    -- The same client retry must never create a second hold.
    CONSTRAINT uq_hold_idempotency_key UNIQUE (idempotency_key)
);

-- The expiry job looks for status = 'HELD' AND expires_at < now.
CREATE INDEX idx_hold_status_expires ON seat_hold (status, expires_at);

CREATE TABLE seat (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT      NOT NULL REFERENCES event (id),
    row_label   VARCHAR(4)  NOT NULL,
    seat_number INTEGER     NOT NULL,
    price_vnd   BIGINT      NOT NULL,
    status      VARCHAR(12) NOT NULL,
    hold_id     UUID REFERENCES seat_hold (id),
    version     BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_seat_position UNIQUE (event_id, row_label, seat_number),
    CONSTRAINT chk_seat_price CHECK (price_vnd >= 0),
    CONSTRAINT chk_seat_status CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD')),
    -- A seat belongs to a hold exactly when it is not available. The database enforces this even
    -- if application code has a bug.
    CONSTRAINT chk_seat_hold CHECK ((status = 'AVAILABLE' AND hold_id IS NULL)
                                 OR (status <> 'AVAILABLE' AND hold_id IS NOT NULL))
);

CREATE INDEX idx_seat_hold ON seat (hold_id);
